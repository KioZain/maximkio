import { createContentsSheet } from "./utils/contentsSheet";

/* ==========================================================================
 * TUNABLE PARAMETERS — всё, что имеет смысл крутить, живёт здесь.
 *
 * Тайминг и кривая живут не тут, а в CSS: --duration-zoom и --ease-out в
 * vars.css. Модуль читает их оттуда, чтобы у сайта не завелось второй семьи
 * кривых. Подписи тоже не тут: заголовок шторки — это текст кнопки, подпись
 * креста приходит атрибутом из словаря (см. блок DATA-ATTRIBUTES ниже).
 * ========================================================================== */

const SETTINGS = {
  // Оглавление кейса. На узком экране оно целиком переезжает внутрь шторки,
  // а на выходе возвращается на своё место в разметке.
  menu: ".O_NavMenu",

  // Кнопка, открывающая шторку. Атрибут — единственный вход в эффект.
  trigger: "[data-contents]",

  /* --- Подписи ---------------------------------------------------------- */

  // Резерв на случай, если на кнопке не оказалось data-contents-close.
  closeLabel: "Закрыть",

  // id заголовка: на него ссылается aria-labelledby диалога.
  titleId: "contents-title",

  /* --- Тайминги (мс) ---------------------------------------------------- */

  // Резерв на случай, если из --duration-zoom ничего не вычиталось.
  duration: 260,

  // Сколько после жеста игнорировать click. Браузер присылает его уже после
  // pointerup, и отличить «отпустил шторку» от «нажал на пункт» можно только
  // по времени. 300 мс хватает на самый медленный из них и всё ещё меньше
  // паузы между двумя осознанными касаниями.
  clickGuard: 300,

  /* --- Жест ------------------------------------------------------------- */

  // Сколько пикселей палец должен пройти вниз, прежде чем шторка поедет за
  // ним. Ниже 4 за жест принимается дрожание при обычном нажатии, выше 10
  // перетаскивание начинает ощущаться залипшим.
  slop: 6,

  // Какую долю своей высоты шторка должна проехать, чтобы отпустить её
  // значило закрыть. Треть — это уже точно намерение: случайно утянуть
  // столько, целясь в пункт списка, не получается.
  dismiss: 0.3,
};

/* ==========================================================================
 * DATA-ATTRIBUTES — переопределения на кнопке:
 *
 *   data-contents         кнопка открывает шторку (без него — обычная кнопка)
 *   data-contents-close   подпись креста для скринридера
 *
 *   <button class="A_Button A_ButtonContents only-mobile"
 *           data-contents data-contents-close="Закрыть">Содержание</button>
 * ========================================================================== */

// Шторка — мобильная замена оглавлению на полях. На широком экране меню стоит
// рядом со статьёй и видно всегда, прятать его в шторку незачем. Порог тот же,
// что и у самого меню, см. O_NavMenu.css.
const mobile = window.matchMedia("(max-width: 768px)");

let sheet = null;

function start() {
  if (sheet) return;

  const trigger = document.querySelector(SETTINGS.trigger);

  sheet = createContentsSheet({
    ...SETTINGS,
    closeLabel: trigger?.dataset.contentsClose || SETTINGS.closeLabel,
  });
}

function stop() {
  if (!sheet) return;
  sheet.destroy();
  sheet = null;
}

// Условие может измениться на живой странице: телефон повернули, окно на
// десктопе сузили до мобильной ширины.
function sync() {
  if (mobile.matches) start();
  else stop();
}

mobile.addEventListener("change", sync);

// Диалог кладётся в конец body, а меню и кнопку надо сначала найти — то и
// другое требует готового документа.
if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", sync);
} else {
  sync();
}
