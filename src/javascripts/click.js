import { createClickPress } from "./utils/clickPress";

/* ==========================================================================
 * TUNABLE PARAMETERS — всё, что имеет смысл крутить, живёт здесь.
 * Точечные переопределения делаются data-атрибутами прямо в разметке
 * (см. блок DATA-ATTRIBUTES ниже).
 *
 * Глубина просадки живёт не тут, а в CSS: --press-scale в E_Click.css.
 * ========================================================================== */

const SETTINGS = {
  // Какие элементы реагируют на нажатие. Класс — единственный вход в эффект.
  selector: ".E_Click",

  /* --- Тайминги (мс) ---------------------------------------------------- */

  // Минимальная длительность нажатия. Клик мышью укладывается в 30–50 мс:
  // без пола элемент дёрнулся бы на пару процентов и вернулся, то есть
  // анимации бы просто не было. 80 — уже читается, ещё не тормозит.
  minPress: 80,

  // Пауза между началом отскока и переходом по ссылке. Отскок длится 140 мс
  // (--duration-press), но ждать его целиком незачем: на кривой ease-out
  // элемент возвращается почти полностью за первую сотню. Больше 200 — клик
  // начинает ощущаться залипшим.
  navDelay: 110,

  /* --- Разное ----------------------------------------------------------- */

  // Насколько далеко можно увести указатель, не потеряв нажатие (px).
  // Это порог «палец поехал в скролл, а не нажимает».
  moveTolerance: 10,
};

/* ==========================================================================
 * DATA-ATTRIBUTES — переопределения на конкретном элементе:
 *
 *   data-click-delay   своя пауза перед переходом, мс (0 — без паузы)
 *   data-click-nav     "off" — не придерживать переход вообще
 *
 *   <a class="A_Button E_Click" data-click-delay="160" href="">Резюме</a>
 *   <a class="A_Button E_Click" data-click-nav="off" href="">Резюме</a>
 * ========================================================================== */

// При prefers-reduced-motion просадки нет (её гасит CSS), а значит и ждать
// ссылке нечего — модуль просто не подключается.
const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)");

let press = null;

function start() {
  if (press) return;
  press = createClickPress(SETTINGS);
}

function stop() {
  if (!press) return;
  press.destroy();
  press = null;
}

// Условие может измениться на живой странице: пользователь включил
// «уменьшить движение» прямо в системных настройках.
function sync() {
  if (reducedMotion.matches) stop();
  else start();
}

reducedMotion.addEventListener("change", sync);

sync();
