/* ==========================================================================
 * scrollLock.js — запрет прокрутки страницы, пока поверх неё что-то открыто.
 *
 * Две функции на весь сайт: их зовут лайтбокс и шторка с оглавлением. Вынесены
 * из лайтбокса не ради красоты, а потому что важна деталь, которую легко
 * потерять при переписывании второй раз: полосу прокрутки надо не просто
 * убрать, а компенсировать её ширину. Без padding-right тело страницы
 * становится шире, и вся центрированная вёрстка под блюром сдвигается вбок
 * ровно в момент открытия.
 *
 * Состояние модульное, а не глобальное: чанки собираются отдельными бандлами,
 * и у каждого свой экземпляр модуля. Это не мешает — одновременно открытых
 * оверлеев на сайте не бывает: лайтбокс живёт только на широком экране,
 * шторка только на узком. Флаг нужен на другое: чтобы повторный вызов не
 * записал в scrollbarGap ноль, посчитанный уже при спрятанной полосе.
 * ========================================================================== */

let locked = false;

export function lockScroll() {
  if (locked) return;
  locked = true;

  const scrollbarGap = window.innerWidth - document.documentElement.clientWidth;

  document.body.style.overflow = "hidden";
  if (scrollbarGap > 0) document.body.style.paddingRight = `${scrollbarGap}px`;
}

export function unlockScroll() {
  if (!locked) return;
  locked = false;

  document.body.style.overflow = "";
  document.body.style.paddingRight = "";
}
