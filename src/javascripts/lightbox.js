import { createImageLightbox } from "./utils/imageLightbox";

/* ==========================================================================
 * TUNABLE PARAMETERS — всё, что имеет смысл крутить, живёт здесь.
 * Точечные переопределения делаются data-атрибутами прямо в разметке
 * (см. блок DATA-ATTRIBUTES ниже).
 *
 * Тайминг и кривая перелёта живут не тут, а в CSS: --duration-zoom и
 * --ease-out в vars.css. Модуль читает их оттуда, чтобы у сайта не завелось
 * второй семьи кривых.
 * ========================================================================== */

const SETTINGS = {
  // Какие картинки можно раскрывать. Атрибут — единственный вход в эффект.
  selector: "[data-zoomable]",

  /* --- Размеры (px) ----------------------------------------------------- */

  // Потолок ширины картинки в модалке. Выше 1066 смысла нет: слот в статье
  // 756, а всё, что шире полутора раз от исходного слота, требует отдельного,
  // более тяжёлого файла — и тогда раскрытие начинает ждать сеть.
  maxWidth: 1066,

  // Отступ от краёв экрана, если CSS почему-то не дал --lightbox-gutter.
  gutter: 40,

  /* --- Тайминги (мс) ---------------------------------------------------- */

  // Резерв на случай, если из --duration-zoom ничего не вычиталось.
  duration: 260,

  /* --- Подписи ---------------------------------------------------------- */

  closeLabel: "Закрыть",
  openLabel: "Открыть картинку крупнее",
};

/* ==========================================================================
 * DATA-ATTRIBUTES — переопределения на конкретной картинке:
 *
 *   data-zoomable      картинку можно раскрыть (без него — обычная картинка)
 *   data-zoom-max      свой потолок ширины в модалке, px
 *   data-zoom-label    своя подпись кнопки для скринридера
 *
 *   <figure class="A_CaseImage" data-zoomable>
 *   <figure class="A_CaseImage" data-zoomable data-zoom-max="880">
 * ========================================================================== */

// Те же три условия, что и в CSS (см. A_CaseImage.css). На узком экране
// картинка и так во всю ширину — раскрывать нечего; на грубом указателе
// нет ни ховера, ни курсора, то есть нечем и предупредить, что клик
// что-то сделает.
const desktop = window.matchMedia(
  "(min-width: 769px) and (hover: hover) and (pointer: fine)",
);

let lightbox = null;

function start() {
  if (lightbox) return;
  lightbox = createImageLightbox(SETTINGS);
}

function stop() {
  if (!lightbox) return;
  lightbox.destroy();
  lightbox = null;
}

// Условие может измениться на живой странице: окно растянули, подключили
// мышь к планшету.
function sync() {
  if (desktop.matches) start();
  else stop();
}

desktop.addEventListener("change", sync);

// Диалог кладётся в конец body, а разметку картинок надо сначала найти —
// то и другое требует готового документа.
if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", sync);
} else {
  sync();
}
